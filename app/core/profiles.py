def get_profile(profile_id: str) -> Profile:
    for profile in ALL_PROFILES:
        if profile.id == profile_id:
            return profile
    return GENERIC


def detect_profile(name: str, description: str = "") -> Profile:
    """Определяет семейство прибора по названию и описанию.

    Название весит больше описания: в описании манометра почти всегда есть
    слово «давление», и без приоритета такой прибор уезжает в профиль
    преобразователя давления. Описание используется, только если по названию
    семейство не определилось.

    Если не угадывается ничего — универсальный профиль: сервис продолжает
    работать, просто подсказки менее точные.
    """

    name_norm = normalize(name)
    description_norm = normalize(description)

    for haystack in (name_norm, description_norm):
        best: Profile | None = None
        best_score = 0
        for profile in ALL_PROFILES:
            if not profile.keywords:
                continue
            score = sum(1 for keyword in profile.keywords if normalize(keyword) in haystack)
            if score > best_score:
                best, best_score = profile, score
        if best is not None:
            return best

    return GENERIC


def find_matching_key(specs: dict[str, str], field: SpecField) -> str | None:
    """Ищет ключ во входных характеристиках по синонимам поля профиля."""
    for key in specs:
        key_norm = normalize(key)
        if any(normalize(synonym) in key_norm for synonym in field.synonyms):
            return key
    return None


def find_missing_fields(
    specs: dict[str, str], profile: Profile, description: str = ""
) -> list[str]:
    """Возвращает канонические ключи полей, которых нет во входных данных.

    Описание тоже считается источником: если характеристика упомянута в
    тексте техпаспорта, нечестно сообщать «данных нет» и запрещать модели
    её использовать.
    """
    description_norm = normalize(description)
    missing: list[str] = []
    for field in profile.fields:
        key = find_matching_key(specs, field)
        if key is not None and specs.get(key, "").strip():
            continue
        if description_norm and any(
            normalize(synonym) in description_norm for synonym in field.synonyms
        ):
            continue
        missing.append(field.key)
    return missing
