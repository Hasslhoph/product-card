"""Профили полноты характеристик по семействам приборов.

Профиль — это не жёсткая схема товара, а подсказка: какие характеристики
для этого класса приборов обычно важны покупателю. Любой товар можно
передать в сервис, даже если профиль для него не нашёлся (``generic``).
"""

from __future__ import annotations

from dataclasses import dataclass

from app.core.text import normalize


@dataclass(frozen=True)
class SpecField:
    key: str
    title: str
    synonyms: tuple[str, ...]
    #: Ключевая характеристика: если её нет, карточка обязательно помечает «данных нет».
    required: bool = False
    #: Подсказка контент-менеджеру, зачем это поле нужно.
    hint: str = ""


@dataclass(frozen=True)
class Profile:
    id: str
    title: str
    keywords: tuple[str, ...]
    fields: tuple[SpecField, ...]


